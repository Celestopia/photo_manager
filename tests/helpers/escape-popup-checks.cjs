const assert = require('node:assert/strict');
module.exports = async ({win, click, waitFor, setValue}) => {
  const evaluate = code => win.webContents.executeJavaScript(code);
  const escape = async (extra = {}) => evaluate(`document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true,...${JSON.stringify(extra)}}))`);
  const open = async selector => { await evaluate(`document.querySelector(${JSON.stringify(selector)}).focus()`); await click(selector); };
  await click('.batch-selection-trigger');
  await open('.gallery-settings-trigger');
  await escape();
  await waitFor(`!document.querySelector('.gallery-settings-menu')`);
  assert.equal(await evaluate(`document.activeElement.matches('.gallery-settings-trigger') && !!document.querySelector('.batch-panel')`),true);
  await open('.batch-panel .location-picker .registry-trigger');
  await escape({isComposing:true});
  await escape({repeat:true});
  assert.equal(await evaluate(`!!document.querySelector('.batch-panel .location-dropdown')`),true);
  await escape();
  await waitFor(`!document.querySelector('.batch-panel .location-dropdown')`);
  assert.equal(await evaluate(`document.activeElement.matches('.batch-panel .location-picker .registry-trigger') && !!document.querySelector('.batch-panel')`),true);
  await setValue('.batch-panel input','Keep this draft');
  await evaluate(`document.querySelector('.batch-panel input').focus()`);
  await escape();
  assert.equal(await evaluate(`document.activeElement.matches('.batch-panel input') && document.activeElement.value==='Keep this draft'`),true);
  await click('.batch-panel .location-picker [data-tip="Create location"]');
  await open('.batch-panel .location-parent-trigger');
  await escape();
  await waitFor(`!document.querySelector('.location-parent-picker .location-dropdown')`);
  assert.equal(await evaluate(`!!document.querySelector('.tag-create-popover')`),true,'Nested menu dismissal leaves editable creation form open');
  await click('.tag-create-actions .btn');
  await click('.batch-close');
  await evaluate(`document.querySelector('.photo-card').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:200,clientY:300}))`);
  await waitFor(`!!document.querySelector('.gallery-media-details-menu')`);
  await escape();
  await waitFor(`!document.querySelector('.gallery-media-details-menu')`);
  await click('.photo-card');
  await waitFor(`!!document.querySelector('.viewer-sidebar-tabs')`);
  await evaluate(`document.querySelector('.image-stage').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:500,clientY:300}))`);
  await waitFor(`!!document.querySelector('.context-menu')`);
  await escape();
  await waitFor(`!document.querySelector('.context-menu')`);
  await evaluate(`Array.from(document.querySelectorAll('.viewer-sidebar-tabs button')).find(b=>b.textContent.includes('Assistant')).click()`);
  await waitFor(`!!document.querySelector('.chat-panel')`);
  await waitFor(`!document.querySelector('button[aria-label="Add attachments"]').disabled`);
  await setValue('[aria-label="Message Assistant"]','Unsent message');
  await open('[aria-label="Add attachments"]');
  await waitFor(`!!document.querySelector('.chat-attachment-menu')`);
  await escape();
  await waitFor(`!document.querySelector('.chat-attachment-menu')`);
  assert.equal(await evaluate(`document.activeElement.matches('[aria-label="Add attachments"]')`),true);
  await open('[aria-label="Session token usage"]');
  await escape();
  await waitFor(`!document.querySelector('.usage-menu')`);
  assert.equal(await evaluate(`document.activeElement.matches('[aria-label="Session token usage"]')`),true);
  await evaluate(`document.querySelector('[aria-label="Message Assistant"]').focus()`);
  await escape();
  assert.equal(await evaluate(`document.activeElement.matches('[aria-label="Message Assistant"]') && document.activeElement.value==='Unsent message'`),true);
  console.log('ESCAPE_POPUP_CHECKS_PASS: focus restoration, composition, repeats, nested menu, batch draft and Assistant draft preservation.');
};
